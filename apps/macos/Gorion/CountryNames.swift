    /// Русское название страны по коду ISO; для редких стран — сам код.
    static func countryName(_ code: String) -> String {
        let upper = code.uppercased()
        // Словарь Flutter — короткие привычные формы («США»); для остальных
        // стран — название из системы, а не двухбуквенный код (Δ к Flutter).
        return countryNames[upper]
            ?? Locale(identifier: "ru_RU").localizedString(forRegionCode: upper)
            ?? upper
    }
